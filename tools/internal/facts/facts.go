// Package facts reads the sibling repositories and writes data/facts.yaml, so
// version numbers on the site are never typed by hand.
package facts

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"strings"

	"gopkg.in/yaml.v3"
)

type Facts struct {
	Generated string                 `yaml:"generated"`
	Projects  map[string]interface{} `yaml:",inline"`
}

type Project struct {
	Name     string   `yaml:"name"`
	Version  string   `yaml:"version"`
	Released string   `yaml:"released"`
	Commits  int      `yaml:"commits"`
	Since    string   `yaml:"since"`
	Go       string   `yaml:"go,omitempty"`
	License  string   `yaml:"license"`
	Repo     string   `yaml:"repo"`
	Binaries []string `yaml:"binaries,omitempty"`
	Apps     []string `yaml:"apps,omitempty"`
}

var (
	projectOrder = []struct {
		dir  string
		name string
	}{
		{"tie", "tie"},
		{"tie-gui", "tie-gui"},
		{"anneal", "anneal"},
		{"fynerisor", "fynerisor"},
	}
	goVersion = regexp.MustCompile(`(?m)^go\s+(\S+)`)
)

// Generate writes data/facts.yaml under root. src is the parent directory that
// holds the sibling checkouts.
func Generate(root, src string) error {
	out := Facts{Generated: "", Projects: map[string]interface{}{}}
	// Use an ordered map via yaml.Node so the file reads nicely.
	doc := &yaml.Node{Kind: yaml.MappingNode}
	add := func(k string, v interface{}) error {
		var n yaml.Node
		if err := n.Encode(v); err != nil {
			return err
		}
		doc.Content = append(doc.Content, &yaml.Node{Kind: yaml.ScalarNode, Value: k}, &n)
		return nil
	}

	generated := strings.TrimSpace(run("", "date", "+%Y-%m-%d"))
	if generated == "" {
		generated = "unknown"
	}
	if err := add("generated", generated); err != nil {
		return err
	}

	for _, p := range projectOrder {
		dir := filepath.Join(src, p.dir)
		if _, err := os.Stat(filepath.Join(dir, ".git")); err != nil {
			continue // the project wasn't checked out; leave the previous entry out
		}
		v, err := readProject(dir, p.name)
		if err != nil {
			return fmt.Errorf("%s: %w", p.dir, err)
		}
		if err := add(p.name, v); err != nil {
			return err
		}
		out.Projects[p.name] = v
	}

	var buf strings.Builder
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(doc); err != nil {
		return err
	}
	header := "# Generated by `make facts`. Do not edit.\n"
	path := filepath.Join(root, "data", "facts.yaml")
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(header+buf.String()), 0o644)
}

func readProject(dir, name string) (Project, error) {
	p := Project{Name: name, Version: "unreleased", License: "BSD-3-Clause"}
	if remote := run(dir, "git", "remote", "get-url", "origin"); remote != "" {
		p.Repo = toHTTPS(remote)
	}
	p.Commits = atoi(run(dir, "git", "rev-list", "--count", "HEAD"))
	p.Since = run(dir, "git", "log", "--reverse", "--format=%cs", "HEAD")
	if p.Since != "" {
		p.Since = strings.Split(p.Since, "\n")[0]
	}
	last := run(dir, "git", "log", "-1", "--format=%cs", "HEAD")
	p.Released = last

	// The latest tag, if there is one. tie-gui and anneal have none.
	tag := run(dir, "git", "describe", "--tags", "--abbrev=0")
	if tag != "" {
		p.Version = tag
		if d := run(dir, "git", "log", "-1", "--format=%cs", tag); d != "" {
			p.Released = d
		}
		// "Since" means the first tagged release, not the first commit in a
		// repository that may carry older history.
		if first := strings.Split(run(dir, "git", "tag", "--sort=creatordate"), "\n")[0]; first != "" {
			if d := run(dir, "git", "log", "-1", "--format=%cs", first); d != "" {
				p.Since = d
			}
		}
	} else if name == "anneal" {
		p.Version = "dev"
	}

	if b, err := os.ReadFile(filepath.Join(dir, "go.mod")); err == nil {
		if m := goVersion.FindSubmatch(b); len(m) == 2 {
			p.Go = string(m[1])
		}
	}

	// Binaries and apps are discovered from cmd/.
	if entries, err := os.ReadDir(filepath.Join(dir, "cmd")); err == nil {
		for _, e := range entries {
			if !e.IsDir() {
				continue
			}
			bin := e.Name()
			if name == "tie-gui" {
				p.Apps = append(p.Apps, bin)
			} else {
				p.Binaries = append(p.Binaries, bin)
			}
		}
	}
	return p, nil
}

func run(dir, name string, args ...string) string {
	cmd := exec.Command(name, args...)
	if dir != "" {
		cmd.Dir = dir
	}
	b, err := cmd.Output()
	if err != nil {
		return ""
	}
	return strings.TrimSpace(string(b))
}

func atoi(s string) int {
	n := 0
	fmt.Sscanf(s, "%d", &n)
	return n
}

func toHTTPS(remote string) string {
	remote = strings.TrimSuffix(remote, ".git")
	if strings.HasPrefix(remote, "git@github.com:") {
		return "https://github.com/" + strings.TrimPrefix(remote, "git@github.com:")
	}
	if strings.HasPrefix(remote, "ssh://git@github.com/") {
		return "https://github.com/" + strings.TrimPrefix(remote, "ssh://git@github.com/")
	}
	return remote
}
